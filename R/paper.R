write_extension_paper <- function() {
  shares <- read_tab("belief_scheme_shares.csv") |> dplyr::filter(kind == "all")
  models <- read_tab("belief_engagement_models.csv") |> dplyr::filter(kind == "all", status == "estimated")
  coverage <- read_tab("belief_index_coverage.csv") |> dplyr::filter(kind == "all", scheme == 1)
  number <- \(x) formatC(x, format = "f", digits = 2)
  p_format <- \(x) ifelse(x < .001, "$<0.001$", formatC(x, format = "f", digits = 3))
  interval <- \(lo, hi) paste0("[", number(lo), ", ", number(hi), "]")
  study_names <- c(alumni = "Alumni", staff = "Staff", mturk_march = "March", mturk_july = "July")
  outcome_names <- c(interest = "Interest", voting_intention = "Voting intention", partisan_intensity = "Intensity")
  state_names <- c(
    knowledge = "Knowledge", correct_belief = "Correct belief",
    incorrect_belief = "Incorrect belief", misinformation = "Misinformation"
  )
  sample_names <- c(complete_items = "Complete", available_items = "Available")
  shares |>
    dplyr::mutate(study = factor(study_names[study], levels = study_names)) |>
    dplyr::arrange(study, sample, scheme) |>
    dplyr::transmute(
      study,
      sample = sample_names[sample], scheme, n,
      dplyr::across(dplyr::all_of(extension_states), \(x) formatC(100 * x, format = "f", digits = 1))
    ) |>
    write_table(
      file.path(table_dir, "belief_schemes.tex"), "llrrrrrrr",
      c("Study", "Items", "Rule", "$n$", "K", "CB", "Mid.", "IB", "M")
    )
  models |>
    dplyr::filter(scheme == 1, sample == "complete_items", term %in% names(state_names)) |>
    dplyr::mutate(
      study = factor(study_names[study], levels = study_names),
      outcome = factor(outcome_names[outcome], levels = outcome_names),
      term = factor(state_names[term], levels = state_names)
    ) |>
    dplyr::arrange(study, outcome, term) |>
    dplyr::transmute(
      study, outcome, term, n,
      mean = number(outcome_mean),
      estimate = number(estimate), interval = interval(lower, upper), p = p_format(p_holm)
    ) |>
    write_table(
      file.path(table_dir, "belief_engagement.tex"), "lllrrrrr",
      c("Study", "Outcome", "State", "$n$", "Mean", "Diff.", "95\\% interval", "$p_H$"),
      caption = "Belief states and engagement: complete-item respondents, Scheme 1",
      label = "tab:engagement"
    )
  models |>
    dplyr::filter(term == "knowledge_minus_misinformation") |>
    dplyr::mutate(
      study = factor(study_names[study], levels = study_names),
      outcome = factor(outcome_names[outcome], levels = outcome_names)
    ) |>
    dplyr::arrange(study, outcome, sample, scheme) |>
    dplyr::transmute(
      study, outcome,
      sample = sample_names[sample], scheme, n,
      estimate = number(estimate), interval = interval(lower, upper), p = p_format(p_holm)
    ) |>
    write_table(
      file.path(table_dir, "belief_contrasts.tex"), "lllrrrrr",
      c("Study", "Outcome", "Items", "Rule", "$n$", "Diff.", "95\\% interval", "$p_H$"),
      caption = "Knowledge versus misinformation: scoring and missing-item sensitivity",
      label = "tab:beliefcontrasts"
    )
  one_model <- function(study, outcome, term, scheme = 1, sample = "complete_items") {
    row <- models[
      models$study == study & models$outcome == outcome & models$term == term &
        models$scheme == scheme & models$sample == sample,
    ]
    stopifnot(nrow(row) == 1)
    row
  }
  march <- shares |> dplyr::filter(study == "mturk_march", sample == "complete_items")
  values <- c(
    extMarchMiddleWide = pct(march$middle[march$scheme == 1], 1),
    extMarchMiddleNarrow = pct(march$middle[march$scheme == 3], 1),
    extJulyComplete = coverage$complete[coverage$study == "mturk_july"],
    extJulyTotal = coverage$respondents[coverage$study == "mturk_july"],
    extJulyAvailable = with(coverage[coverage$study == "mturk_july", ], respondents - no_ratings),
    extMarchComplete = coverage$complete[coverage$study == "mturk_march"]
  )
  picks <- list(
    extMarchInterestK = one_model("mturk_march", "interest", "knowledge"),
    extMarchInterestM = one_model("mturk_march", "interest", "misinformation"),
    extMarchIntensity = one_model("mturk_march", "partisan_intensity", "knowledge_minus_misinformation"),
    extMarchVoteK = one_model("mturk_march", "voting_intention", "knowledge"),
    extMarchVoteM = one_model("mturk_march", "voting_intention", "misinformation"),
    extMarchVoteDiff = one_model("mturk_march", "voting_intention", "knowledge_minus_misinformation"),
    extMarchVoteLenient = one_model("mturk_march", "voting_intention", "knowledge_minus_misinformation", 2),
    extJulyVoteComplete = one_model("mturk_july", "voting_intention", "knowledge_minus_misinformation"),
    extJulyVoteAvailable = one_model(
      "mturk_july", "voting_intention", "knowledge_minus_misinformation",
      sample = "available_items"
    )
  )
  for (name in names(picks)) {
    row <- picks[[name]]
    values <- c(values, stats::setNames(
      c(number(row$estimate), interval(row$lower, row$upper), number(row$outcome_mean)),
      c(name, paste0(name, "CI"), paste0(name, "Mean"))
    ))
  }
  write_macros(values, file.path(table_dir, "extension_macros.tex"))
}
